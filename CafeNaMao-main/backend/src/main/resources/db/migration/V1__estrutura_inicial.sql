-- Estrutura inicial do Café na Mão.
-- Os tipos são compatíveis com H2 e PostgreSQL; os valores monetários usam
-- NUMERIC(10,2) e nunca ponto flutuante.

CREATE TABLE bebida (
    id        VARCHAR(120)  NOT NULL,
    nome      VARCHAR(120)  NOT NULL,
    descricao VARCHAR(500)  NOT NULL,
    categoria VARCHAR(80)   NOT NULL,
    preco     NUMERIC(10,2) NOT NULL,
    ordem     INTEGER       NOT NULL,
    CONSTRAINT pk_bebida PRIMARY KEY (id)
);

CREATE TABLE pedido (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY,
    numero          VARCHAR(20)  NOT NULL,
    criado_em       TIMESTAMP    NOT NULL,
    forma_pagamento VARCHAR(30)  NOT NULL,
    status          VARCHAR(30)  NOT NULL,
    CONSTRAINT pk_pedido PRIMARY KEY (id),
    CONSTRAINT uq_pedido_numero UNIQUE (numero)
);

CREATE TABLE pedido_item (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY,
    pedido_id        BIGINT        NOT NULL,
    ordem            INTEGER       NOT NULL,
    bebida_id        VARCHAR(120)  NOT NULL,
    bebida_nome      VARCHAR(120)  NOT NULL,
    bebida_descricao VARCHAR(500)  NOT NULL,
    bebida_categoria VARCHAR(80)   NOT NULL,
    bebida_preco     NUMERIC(10,2) NOT NULL,
    quantidade       INTEGER       NOT NULL,
    CONSTRAINT pk_pedido_item PRIMARY KEY (id),
    CONSTRAINT fk_pedido_item_pedido FOREIGN KEY (pedido_id)
        REFERENCES pedido (id) ON DELETE CASCADE,
    CONSTRAINT uq_pedido_item_ordem UNIQUE (pedido_id, ordem)
);

CREATE INDEX idx_pedido_criado_em ON pedido (criado_em);
